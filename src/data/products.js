// Utility functions for filtering
export const getUniqueCategories = () => {
  const categories = [...new Set(products.map(p => p.category))];
  return categories;
};

export const getUniqueSports = () => {
  const sports = [...new Set(products.map(p => p.sport))];
  return sports;
};

export const getProductsByCategory = (category) => {
  return products.filter(p => p.category === category);
};

export const getProductsBySport = (sport) => {
  return products.filter(p => p.sport === sport);
};

export const getFeaturedProducts = () => {
  return products.filter(p => p.featured);
};

export const getProductsBySubCategory = (category, subCategory) => {
  return products.filter(p => p.category === category && p.subCategory === subCategory);
};

// Get customizable products only
export const getCustomizableProducts = () => {
  return products.filter(p => p.customizable && p.customizable.length > 0);
};

// Get products by customization option
export const getProductsByCustomization = (option) => {
  return products.filter(p => p.customizable && p.customizable.includes(option));
};

export default products;